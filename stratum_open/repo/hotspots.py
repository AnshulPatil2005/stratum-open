"""Hotspots: source files that change often and are hard to follow, where a
mistake is both likely and costly.

Churn is the number of commits on `ref` that touched a file in the window,
counted under the file's name at `ref`: when git sees a rename (`-M`, at least
half the content kept), the old name's commits carry over. A rename that
rewrote most of the file starts its count again.

Complexity is a rough, language-blind count of decision points in the file at
`ref`: `if elif elsif for foreach while until unless case when catch except
rescue`, `&&`, `||`, `??`, a ternary `?` (not `?.` or TypeScript's `x?:`), and
Python's and Ruby's `and` and `or`, with comments and string literals left
out roughly (`#` comments for Python, Ruby, shell and the like, `//` and
`/* */` for the rest). It ranks files, it isn't a metric to quote.

A file is a hotspot when it changed at least twice and is at least as complex
as the median source file changed in the window, so a busy but simple file
(a version number, a list of constants) isn't one; or when two or more of the
commits that touched it were reverts or hotfixes, however simple it is.
Hotspots rank by churn × complexity, those with repeated fixes first. Tests
are left out: they change with the code they test and are seldom where the
risk is. So are generated, minified and vendored files and files over 1 MB;
drop anything else the policy ignores before using the result.
"""

from __future__ import annotations

import posixpath
import re
import statistics
import subprocess
from collections import Counter
from dataclasses import dataclass
from datetime import datetime
from typing import Iterable

from stratum_open.repo.history import Commit, recent_commits

MAX_BYTES = 1_000_000
MIN_CHURN = 2
MIN_FIXES = 2  # reverts and hotfixes that make a file a hotspot on their own
MINIFIED_LINE_CHARS = 200  # average non-blank line length past which a file is minified
SOURCE_EXTENSIONS = frozenset({
    ".py", ".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs", ".mts", ".cts", ".vue", ".svelte",
    ".go", ".rs", ".java", ".kt", ".kts", ".scala", ".groovy", ".cs", ".fs", ".swift", ".dart",
    ".c", ".h", ".cc", ".cpp", ".cxx", ".hpp", ".hh", ".m", ".mm", ".zig",
    ".rb", ".php", ".pl", ".pm", ".sh", ".bash", ".lua", ".r", ".ex", ".exs", ".erl", ".jl", ".nim",
})
_HASH_COMMENTS = frozenset({".py", ".rb", ".pl", ".pm", ".sh", ".bash", ".r", ".ex", ".exs", ".jl", ".nim"})
_SKIP_FOLDERS = frozenset({"vendor", "third_party", "node_modules", "dist", "build", "generated", "__generated__"})
_TEST_FOLDERS = frozenset({"test", "tests", "__tests__", "spec", "specs"})
_TEST_FILE = re.compile(r"^(?:test_.*|.*_test|.*\.(?:test|spec)|conftest|.*[a-z0-9]Tests?)\.\w+$")
_GENERATED_FILE = re.compile(r"\.min\.|\.d\.ts$|_pb2(?:_grpc)?\.py$|\.pb\.go$|\.(?:generated|g)\.\w+$|\.lock$", re.IGNORECASE)
# A generator's header, not a file that merely mentions the word.
_GENERATED_HEADER = re.compile(r"@generated|DO NOT EDIT|(?i:auto-?generated by)")

# An unterminated comment or string runs to the end of the file, as it would for the compiler.
_STRING = r""""(?:\\.|[^"\\\n])*"|'(?:\\.|[^'\\\n])*'"""
_HASH_NOISE = re.compile(r'"""[\s\S]*?(?:"""|\Z)|\'\'\'[\s\S]*?(?:\'\'\'|\Z)|' + _STRING + r"|#[^\n]*")
_SLASH_NOISE = re.compile(_STRING + r"|`(?:\\.|[^`\\])*(?:`|\Z)|//[^\n]*|/\*[\s\S]*?(?:\*/|\Z)")
_KEYWORDS = re.compile(r"\b(?:if|elif|elsif|for|foreach|while|until|unless|case|when|catch|except|rescue)\b")
_OPERATORS = re.compile(r"&&|\|\||\?\?")
_WORDS = re.compile(r"\b(?:and|or)\b")  # Python's and Ruby's
_TERNARY = re.compile(r"(?<![?.])\?(?![?.:])")  # not ?. or ?? or TypeScript's optional x?:
_SPACED_TERNARY = re.compile(r"(?<=\s)\?(?=\s)")
_FIX = re.compile(r"^revert\b|\bhot[ -]?fix", re.IGNORECASE)


@dataclass(frozen=True)
class Hotspot:
    path: str
    churn: int  # commits that touched it in the window
    complexity: int  # decision points in the file at `ref`
    score: int  # churn × complexity
    window_days: int = 180
    fixes: int = 0  # of those commits, reverts and hotfixes
    complex: bool = True  # at least the median complexity


@dataclass(frozen=True)
class Measure:
    loc: int  # non-blank lines of code, comments left out
    complexity: int  # 1 + decision points
    nesting: int  # deepest block


def hotspots(
    repo_dir: str,
    ref: str = "HEAD",
    *,
    window_days: int = 180,
    top: int = 10,
    now: datetime | None = None,
) -> list[Hotspot]:
    """The `top` hotspots on `ref`, worst first. Short history means few or none."""
    churn, fixes = _churn(recent_commits(repo_dir, ref, window_days=window_days, now=now))
    texts = _read_at(repo_dir, ref, sorted(path for path in churn if is_source(path)))
    complexity = {path: decision_points(path, text) for path, text in texts.items() if not generated(text)}
    if not complexity:
        return []
    median = statistics.median(complexity.values())
    found = [
        Hotspot(path, churn[path], points, churn[path] * points, window_days, fixes[path], bool(points) and points >= median)
        for path, points in complexity.items()
        if (churn[path] >= MIN_CHURN and points and points >= median) or fixes[path] >= MIN_FIXES
    ]
    found.sort(key=lambda h: (h.fixes < MIN_FIXES, -h.score, -h.churn, h.path))
    return found[:top]


def hotspot_paths(hotspots: Iterable[Hotspot]) -> set[str]:
    return {hotspot.path for hotspot in hotspots}


def hotspot_note(hotspots: Iterable[Hotspot], changed_paths: Iterable[str]) -> list[str]:
    """A line for each changed file that is a hotspot, in the PR's order."""
    by_path = {hotspot.path: hotspot for hotspot in hotspots}
    notes = []
    for path in dict.fromkeys(changed_paths):
        hotspot = by_path.get(path)
        if hotspot is not None:
            fixes = f", {hotspot.fixes} of them reverts or hotfixes" if hotspot.fixes else ""
            complex_ = f", and among the more complex files ({hotspot.complexity} branches and conditions)" if hotspot.complex else ""
            notes.append(f"`{path}` is a hotspot: changed {hotspot.churn} times in the last {hotspot.window_days} days"
                         f"{fixes}{complex_}. Reviewed strictly.")
    return notes


def is_source(path: str) -> bool:
    """Code someone maintains by hand: not a test, generated, minified or
    vendored file, going by its path. `generated` reads the text too."""
    folders, name = path.split("/")[:-1], posixpath.basename(path)
    return (
        posixpath.splitext(name)[1].lower() in SOURCE_EXTENSIONS
        and not _GENERATED_FILE.search(name)
        and not _TEST_FILE.match(name)
        and not any(folder in _TEST_FOLDERS or folder in _SKIP_FOLDERS for folder in folders)
    )


def generated(text: str) -> bool:
    """A generator's header in the first lines, or lines too long to be written by hand."""
    lines = [line for line in text.splitlines() if line.strip()]
    if not lines:
        return False
    return bool(_GENERATED_HEADER.search("\n".join(lines[:5]))) or sum(map(len, lines)) / len(lines) > MINIFIED_LINE_CHARS


def decision_points(path: str, text: str) -> int:
    return _count(_hash_family(path), _code(path, text))


def measure(path: str, text: str) -> Measure | None:
    """Lines of code, complexity and nesting depth of one file, or None for a
    file that isn't hand-maintained source."""
    if not is_source(path) or len(text) > MAX_BYTES or generated(text):
        return None
    hash_family = _hash_family(path)
    code = _code(path, text)
    lines = [line for line in code.split("\n") if line.strip()]
    if hash_family:
        # A continuation line, inside a bracket opened above it, is aligned
        # however its author liked: it sets neither the depth nor the unit.
        indents, open_ = [], 0
        for line in lines:
            if open_ == 0:
                indents.append(len(line) - len(line.lstrip(" ")))
            open_ = max(0, open_ + sum(map(line.count, "([{")) - sum(map(line.count, ")]}")))
        steps = Counter(b - a for a, b in zip(indents, indents[1:]) if b > a)
        unit = steps.most_common(1)[0][0] if steps else 4
        nesting = max((width // unit for width in indents), default=0)
    else:
        depth = nesting = 0
        for brace in re.findall(r"[{}]", code):
            depth = depth + 1 if brace == "{" else max(0, depth - 1)
            nesting = max(nesting, depth)
    return Measure(len(lines), 1 + _count(hash_family, code), nesting)


def _hash_family(path: str) -> bool:
    return posixpath.splitext(path)[1].lower() in _HASH_COMMENTS


def _code(path: str, text: str) -> str:
    """The text with comments blanked and strings emptied, newlines kept."""
    noise = _HASH_NOISE if _hash_family(path) else _SLASH_NOISE

    def blank(match: re.Match) -> str:
        found = match.group(0)
        return ('""' if found[0] in "\"'`" else " ") + "\n" * found.count("\n")

    return noise.sub(blank, text.replace("\t", "    "))


def _count(hash_family: bool, code: str) -> int:
    points = len(_KEYWORDS.findall(code)) + len(_OPERATORS.findall(code))
    if hash_family:  # Ruby's `nil?` is a name, not a ternary; its ternary has a space either side
        return points + len(_WORDS.findall(code)) + len(_SPACED_TERNARY.findall(code))
    return points + len(_TERNARY.findall(code))


def _churn(commits: list[Commit]) -> tuple[Counter, Counter]:
    """Commits, and reverts and hotfixes, per file, newest first, under each
    file's latest name."""
    counts: Counter = Counter()
    fixes: Counter = Counter()
    later_name: dict[str, str] = {}  # a name a file had then -> its name at `ref`
    for commit in commits:
        fix = bool(_FIX.search(commit.subject))
        for change in commit.changes:
            current = later_name.get(change.path, change.path)
            counts[current] += 1
            fixes[current] += fix
            if change.status == "R" and change.old_path:
                later_name[change.old_path] = current
    return counts, fixes


def _read_at(repo_dir: str, ref: str, paths: list[str]) -> dict[str, str]:
    """Each file's text at `ref`, in one git call. Files gone by then, and
    files over MAX_BYTES, are left out."""
    paths = [path for path in paths if "\n" not in path]
    if not paths:
        return {}
    request = "".join(f"{ref}:{path}\n" for path in paths).encode("utf-8")
    out = subprocess.run(
        ["git", "-C", repo_dir, "cat-file", "--batch"], input=request, capture_output=True, timeout=120, check=True,
    ).stdout
    texts, pos = {}, 0
    for path in paths:
        end = out.find(b"\n", pos)
        if end < 0:
            break
        header = out[pos:end].split(b" ")
        pos = end + 1
        if len(header) == 3 and header[2].isdigit():  # "<sha> <type> <size>", then the content
            size = int(header[2])
            if header[1] == b"blob" and size <= MAX_BYTES:
                texts[path] = out[pos:pos + size].decode("utf-8", errors="replace")
            pos += size + 1
    return texts
